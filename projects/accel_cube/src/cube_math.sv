// ---- helper functions and wires (combinational, used at fixed steps)
// camera coordinate of corner kk: the signed sum of a row of cl
function automatic signed [17:0] camsum(input [2:0] kk, input signed [15:0] c0, input signed [15:0] c1,
                                        input signed [15:0] c2);
	reg signed [17:0] t0, t1, t2;
	begin
		t0 = {{2{c0[15]}}, c0}; t1 = {{2{c1[15]}}, c1}; t2 = {{2{c2[15]}}, c2};
		camsum = (kk[0] ? t0 : -t0) + (kk[1] ? t1 : -t1) + (kk[2] ? t2 : -t2);
	end
endfunction
