// Per-frame math of the accelerometer cube: one sequential engine, started by the frame tick inside the
// vertical blanking, done about 1,000 clocks later. It mirrors frame_math() in assets/model.py step by step:
// squares and roots of the two vectors -> orientation from the steady one (held below 0.25 g) -> pitch /
// roll by CORDIC, (cos, sin) of the view yaw -> rotation matrix -> the 8 projected corners -> the visible
// faces (shade, 4 edge functions each) -> the live vector's numbers as BCD -> the vector widget's 8 line
// segments. One 18x18 multiplier, one divider, one square root, one CORDIC and one binary-to-BCD converter
// are shared by every step.
// ***********************************************
`default_nettype none

module cube_math (
	input		wire						clk,
	input		wire						rst,
	input		wire						start,			// frame tick; ignored while busy
	input		wire	signed	[15:0]	gx,				// the steady vector (filtered): the cube, pitch, roll. Q4, 1 g = 4096
	input		wire	signed	[15:0]	gy,
	input		wire	signed	[15:0]	gz,
	input		wire	signed	[15:0]	ax,				// the live vector (raw): the arrow, the bars, the numbers, the peak
	input		wire	signed	[15:0]	ay,
	input		wire	signed	[15:0]	az,
	input		wire	signed	[15:0]	psi,				// view yaw, BAM16
	input		wire						peak_clr,		// sampled at start: restart the peak from this frame
	output	logic						busy,
	output	logic						done,
	// the cube: up to 3 visible faces (slots), 4 edge units each; E(x, y) = ((x dy - y dx) << 4) + c
	output	logic	[2:0]				slot_valid,
	output	logic	[2:0][11:0]		slot_rgb,
	output	logic	[11:0][15:0]	e_dx,
	output	logic	[11:0][15:0]	e_dy,
	output	logic	[11:0][31:0]	e_c,
	output	logic	[11:0][23:0]	e_t,				// edge line: |E| <= T
	// the vector widget: 8 segments, first hit wins
	output	logic	[7:0]				sg_valid,
	output	logic	[7:0]				sg_dash,
	output	logic	[7:0][11:0]		sg_rgb,
	output	logic	[7:0][17:0]		sg_dx,
	output	logic	[7:0][17:0]		sg_dy,
	output	logic	[7:0][31:0]		sg_c,
	output	logic	[7:0][23:0]		sg_t,
	output	logic	[7:0][9:0]		sg_xmin,
	output	logic	[7:0][9:0]		sg_xmax,
	output	logic	[7:0][9:0]		sg_ymin,
	output	logic	[7:0][9:0]		sg_ymax,
	// the numbers: 0 x, 1 y, 2 z, 3 |a|, 4 peak (mg); 5 pitch, 6 roll (0.1 degree), 4 BCD digits each
	output	logic	[6:0][15:0]		bcd4,
	output	logic	[2:0][19:0]		bcd5,				// |ax|, |ay|, |az| in Q4 counts, 5 digits (the report line)
	output	logic	[4:0]				neg,				// signs: x, y, z, pitch, roll
	output	logic	[2:0][9:0]		bar_len,			// bar lengths in pixels (1 g = 56)
	output	logic	[2:0]				bar_neg,
	output	logic	[15:0]			mag				// |a| in Q4 counts (the 7-segment display)
	);

