	case ({f, ee})
		{3'd0, 2'd0}: vidx = 3'd1; {3'd0, 2'd1}: vidx = 3'd3; {3'd0, 2'd2}: vidx = 3'd7; {3'd0, 2'd3}: vidx = 3'd5;
		{3'd1, 2'd0}: vidx = 3'd0; {3'd1, 2'd1}: vidx = 3'd4; {3'd1, 2'd2}: vidx = 3'd6; {3'd1, 2'd3}: vidx = 3'd2;
		{3'd2, 2'd0}: vidx = 3'd2; {3'd2, 2'd1}: vidx = 3'd6; {3'd2, 2'd2}: vidx = 3'd7; {3'd2, 2'd3}: vidx = 3'd3;
		{3'd3, 2'd0}: vidx = 3'd0; {3'd3, 2'd1}: vidx = 3'd1; {3'd3, 2'd2}: vidx = 3'd5; {3'd3, 2'd3}: vidx = 3'd4;
