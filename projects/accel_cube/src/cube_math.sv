// ---- the engine. Default: next step; a waiting step holds with k <= k.
always_ff @(posedge clk) begin
	div_start <= 1'b0;
	sq_start <= 1'b0;
	cr_start <= 1'b0;
	bcd_start <= 1'b0;
	done <= 1'b0;
	k <= k + 5'd1;
	if (rst) begin
		phase <= P_IDLE;
		k <= 5'd0;
		busy <= 1'b0;
		sth <= 16'sd0;
		cth <= 16'sd16384;
		sph <= 16'sd0;
		cph <= 16'sd16384;
		peak2 <= 32'd0;
		slot_valid <= 3'b000;
		sg_valid <= 8'h00;
		bcd4 <= 112'd0;
		bcd5 <= 60'd0;
		neg <= 5'd0;
		bar_len <= 30'd0;
		bar_neg <= 3'd0;
		mag <= 16'd0;
	end else case (phase)

	P_IDLE: begin
		k <= 5'd0;
		if (start) begin
			lgx <= gx; lgy <= gy; lgz <= gz;
			lax <= ax; lay <= ay; laz <= az; lpsi <= psi; lclr <= peak_clr;
			busy <= 1'b1;
			phase <= P_SQ;
		end
	end

	// squares, then |g|, r = sqrt(gy^2 + gz^2) and |a| (the square root takes 16 clocks each)
	P_SQ: case (k)
		5'd0: begin ma <= lgx18; mb <= lgx18; end
		5'd1: begin acc <= prod40; ma <= lgy18; mb <= lgy18; end
		5'd2: begin g2 <= acc_p[31:0]; rg2 <= prod40[31:0]; ma <= lgz18; mb <= lgz18; end
		5'd3: begin g2 <= g2 + prod40[31:0]; rg2 <= rg2 + prod40[31:0]; ma <= lax18; mb <= lax18; end
		5'd4: begin acc <= prod40; ma <= lay18; mb <= lay18; end
		5'd5: begin a2 <= acc_p[31:0]; ma <= laz18; mb <= laz18; end
		5'd6: begin a2 <= a2 + prod40[31:0]; sq_start <= 1'b1; sq_v <= g2; end
		5'd7: if (sq_done) begin mag_g <= sq_r; sq_start <= 1'b1; sq_v <= rg2; end else k <= k;
		5'd8: if (sq_done) begin r_g <= sq_r; sq_start <= 1'b1; sq_v <= a2; end else k <= k;
		default: if (sq_done) begin mag_a <= sq_r; phase <= P_ANG; k <= 5'd0; end else k <= k;
	endcase

	// orientation: sin/cos of pitch from gx and |g|, of roll from gy, gz and r; held when too small
	P_ANG: case (k)
		5'd0: if (mag_g >= HOLD_MAG) begin
				div_start <= 1'b1; div_num <= {2'b00, abs_gx, 14'b0}; div_den <= mag_g;
			end else begin phase <= P_CRD; k <= 5'd0; end
		5'd1: if (div_done) begin
				sth <= lgx[15] ? q16s : -q16s;
				div_start <= 1'b1; div_num <= {2'b00, r_g, 14'b0}; div_den <= mag_g;
			end else k <= k;
		5'd2: if (div_done) begin
				cth <= q16s;
				if (r_g >= HOLD_R) begin
					div_start <= 1'b1; div_num <= {2'b00, abs_gy, 14'b0}; div_den <= r_g;
				end else begin phase <= P_CRD; k <= 5'd0; end
			end else k <= k;
		5'd3: if (div_done) begin
				sph <= lgy[15] ? -q16s : q16s;
				div_start <= 1'b1; div_num <= {2'b00, abs_gz, 14'b0}; div_den <= r_g;
			end else k <= k;
		default: if (div_done) begin cph <= lgz[15] ? -q16s : q16s; phase <= P_CRD; k <= 5'd0; end else k <= k;
	endcase

	// CORDIC: pitch = atan2(sth, cth), roll = atan2(sph, cph), (cos, sin) of the yaw
	P_CRD: case (k)
		5'd0: begin
			cr_start <= 1'b1; cr_vec <= 1'b1;
			cr_x0 <= cth[15] ? -cth20 : cth20;
			cr_y0 <= cth[15] ? -sth20 : sth20;
			cr_z0 <= cth[15] ? {1'b1, 19'b0} : 20'sd0;
		end
		5'd1: if (cr_done) begin
				pitch <= zr[19:4];
				cr_start <= 1'b1; cr_vec <= 1'b1;
				cr_x0 <= cph[15] ? -cph20 : cph20;
				cr_y0 <= cph[15] ? -sph20 : sph20;
				cr_z0 <= cph[15] ? {1'b1, 19'b0} : 20'sd0;
			end else k <= k;
		5'd2: if (cr_done) begin
				roll <= zr[19:4];
				cr_start <= 1'b1; cr_vec <= 1'b0;
				cr_x0 <= psi_big ? -x0_20 : x0_20;
				cr_y0 <= 20'sd0;
				cr_z0 <= {psi_big ? lpsi ^ 16'h8000 : lpsi, 4'b0000};
			end else k <= k;
		default: if (cr_done) begin cps <= xr2[17:2]; sps <= yr2[17:2]; phase <= P_MAT; k <= 5'd0; end else k <= k;
	endcase

	// the view matrix: P = camera(30 deg) x Rz(psi) x Ry(theta) x Rx(phi), all Q14 (model: m0, m1, m2, p)
	P_MAT: case (k)
		5'd0:  begin ma <= {{2{sth[15]}}, sth}; mb <= {{2{sph[15]}}, sph}; end
		5'd1:  begin a01 <= p14[17:0]; ma <= {{2{sth[15]}}, sth}; mb <= {{2{cph[15]}}, cph}; end
		5'd2:  begin a02 <= p14[17:0]; ma <= {{2{cth[15]}}, cth}; mb <= {{2{sph[15]}}, sph}; end
		5'd3:  begin a21 <= p14[17:0]; ma <= {{2{cth[15]}}, cth}; mb <= {{2{cph[15]}}, cph}; end
		5'd4:  begin a22 <= p14[17:0]; ma <= {{2{cps[15]}}, cps}; mb <= {{2{cth[15]}}, cth}; end
		5'd5:  begin pm[0] <= p14[17:0]; ma <= {{2{cps[15]}}, cps}; mb <= a01; end
		5'd6:  begin acc <= prod40; ma <= {{2{sps[15]}}, sps}; mb <= {{2{cph[15]}}, cph}; end
		5'd7:  begin pm[1] <= am14[17:0]; ma <= {{2{cps[15]}}, cps}; mb <= a02; end
		5'd8:  begin acc <= prod40; ma <= {{2{sps[15]}}, sps}; mb <= {{2{sph[15]}}, sph}; end
		5'd9:  begin pm[2] <= ap14[17:0]; ma <= {{2{sps[15]}}, sps}; mb <= {{2{cth[15]}}, cth}; end
		5'd10: begin m1[0] <= p14[17:0]; ma <= {{2{sps[15]}}, sps}; mb <= a01; end
		5'd11: begin acc <= prod40; ma <= {{2{cps[15]}}, cps}; mb <= {{2{cph[15]}}, cph}; end
		5'd12: begin m1[1] <= ap14[17:0]; ma <= {{2{sps[15]}}, sps}; mb <= a02; end
		5'd13: begin acc <= prod40; ma <= {{2{cps[15]}}, cps}; mb <= {{2{sph[15]}}, sph}; end
		5'd14: begin m1[2] <= am14[17:0]; ma <= {{2{SE[15]}}, SE}; mb <= m1[0]; end
		// m2 = (-sth, a21, a22); rows 1 and 2 of P from m1 and m2
		5'd15: begin acc <= prod40; ma <= {{2{CE[15]}}, CE}; mb <= -{{2{sth[15]}}, sth}; end
		5'd16: begin pm[3] <= ap14[17:0]; ma <= {{2{CE[15]}}, CE}; mb <= m1[0]; end
		5'd17: begin acc <= prod_neg; ma <= {{2{SE[15]}}, SE}; mb <= -{{2{sth[15]}}, sth}; end
		5'd18: begin pm[6] <= ap14[17:0]; ma <= {{2{SE[15]}}, SE}; mb <= m1[1]; end
		5'd19: begin acc <= prod40; ma <= {{2{CE[15]}}, CE}; mb <= a21; end
		5'd20: begin pm[4] <= ap14[17:0]; ma <= {{2{CE[15]}}, CE}; mb <= m1[1]; end
		5'd21: begin acc <= prod_neg; ma <= {{2{SE[15]}}, SE}; mb <= a21; end
		5'd22: begin pm[7] <= ap14[17:0]; ma <= {{2{SE[15]}}, SE}; mb <= m1[2]; end
		5'd23: begin acc <= prod40; ma <= {{2{CE[15]}}, CE}; mb <= a22; end
		5'd24: begin pm[5] <= ap14[17:0]; ma <= {{2{CE[15]}}, CE}; mb <= m1[2]; end
		5'd25: begin acc <= prod_neg; ma <= {{2{SE[15]}}, SE}; mb <= a22; end
		default: begin pm[8] <= ap14[17:0]; phase <= P_COL; k <= 5'd0; end
	endcase

	// the columns scaled by the half edge: cl[i] = (P[i] * S_Q4) >> 14
	P_COL: begin
		if (k != 5'd0) cl[k - 5'd1] <= p14[15:0];
		if (k != 5'd9) begin ma <= pm[k[3:0]]; mb <= {{2{S_Q4[15]}}, S_Q4}; end
		else begin phase <= P_VERT; k <= 5'd0; idx <= 4'd0; end
	end

	// the 8 corners: camera coordinates, then perspective x = CX + D cam0 / (D - cam2)
	P_VERT: case (k)
		5'd0: begin ma <= {{2{D_Q4[15]}}, D_Q4}; mb <= cam0; end
		5'd1: begin
			div_start <= 1'b1; div_num <= prod_abs[31:0]; div_den <= den16; vsg <= prod40[39];
			ma <= {{2{D_Q4[15]}}, D_Q4}; mb <= cam1;
		end
		5'd2: if (div_done) begin
				vx[idx[2:0]] <= vsg ? CX_Q4 - q16s : CX_Q4 + q16s;
				div_start <= 1'b1; div_num <= prod_abs[31:0]; div_den <= den16; vsg <= prod40[39];
			end else k <= k;
		default: if (div_done) begin
				vy[idx[2:0]] <= vsg ? CY_Q4 + q16s : CY_Q4 - q16s;
				k <= 5'd0;
				if (idx == 4'd7) begin phase <= P_FACE; idx <= 4'd0; s <= 2'd0; end
				else idx <= idx + 4'd1;
			end else k <= k;
	endcase

	// the faces: skip the hidden ones, shade the visible ones, 4 edge units each into slot s
	P_FACE: case (k)
		5'd0: begin
			if (idx == 4'd6) begin
				slot_valid <= {s > 2'd2, s > 2'd1, s != 2'd0};
				phase <= P_NUMS; k <= 5'd0; idx <= 4'd0;
			end else if (n2 < VIS18) begin
				idx <= idx + 4'd1; k <= 5'd0;
			end else begin ma <= n0; mb <= {{2{LX[15]}}, LX}; end
		end
		5'd1: begin acc <= prod40; ma <= n1; mb <= {{2{LY[15]}}, LY}; end
		5'd2: begin acc <= acc_p; ma <= n2; mb <= {{2{LZ[15]}}, LZ}; end
		5'd3: begin nl <= ap14[15:0]; end
		5'd4: begin ma <= nl[15] ? 18'sd0 : {2'b00, nl}; mb <= SHADE_RANGE; end
		5'd5: begin bb <= SHADE_MIN + p14[9:0]; end
		5'd6: begin ma <= {8'b0, bb}; mb <= {14'b0, fcol[11:8]}; end
		5'd7: begin sr <= p8[3:0]; ma <= {8'b0, bb}; mb <= {14'b0, fcol[7:4]}; end
		5'd8: begin sg <= p8[3:0]; ma <= {8'b0, bb}; mb <= {14'b0, fcol[3:0]}; end
		5'd9: begin sb <= p8[3:0]; e <= 2'd0; end
		5'd10: begin edx <= vx[vj] - vx[vi]; edy <= vy[vj] - vy[vi]; xi <= vx[vi]; yi <= vy[vi]; end
		5'd11: begin ma <= 18'sd8 - {{2{xi[15]}}, xi}; mb <= {{2{edy[15]}}, edy}; end
		5'd12: begin acc <= prod40; ma <= 18'sd8 - {{2{yi[15]}}, yi}; mb <= {{2{edx[15]}}, edx}; end
		default: begin
			e_c[{s, e}] <= acc_m[31:0];
			e_dx[{s, e}] <= edx;
			e_dy[{s, e}] <= edy;
			e_t[{s, e}] <= e_tv;
			if (e == 2'd3) begin
				slot_rgb[s] <= {sr, sg, sb};
				s <= s + 2'd1; idx <= idx + 4'd1; k <= 5'd0;
			end else begin e <= e + 2'd1; k <= 5'd10; end
		end
	endcase

	// the numbers (all from the live vector): peak, then x y z |a| peak in mg and pitch roll in 0.1 degree
	P_NUMS: case (k)
		5'd0: begin
			peak2 <= (lclr || a2 > peak2) ? a2 : peak2;
			neg <= {roll[15], pitch[15], laz[15], lay[15], lax[15]};
			bar_len[0] <= b7x[18:9];
			bar_len[1] <= b7y[18:9];
			bar_len[2] <= b7z[18:9];
			bar_neg <= {laz[15], lay[15], lax[15]};
			mag <= mag_a;
		end
		5'd1: begin sq_start <= 1'b1; sq_v <= peak2; end
		5'd2: if (sq_done) peak_mag <= sq_r; else k <= k;
		default: begin						// kn = 0..7: load number kn, store number kn - 1 (multiplies pipelined)
			if (kn < 5'd7) begin ma <= {2'b00, nval}; mb <= (kn < 5'd5) ? 18'sd125 : 18'sd3600; end
			if (kn != 5'd0) numv[kn[2:0] - 3'd1] <= (kn <= 5'd5) ? r_mg[15:0] : r_deg[15:0];
			if (kn == 5'd7) begin phase <= P_WDG; k <= 5'd0; end
		end
	endcase

	// the vector widget: tip and shadow of the acceleration arrow under the fixed view, the arrowhead
	P_WDG: case (k)
		5'd0:  begin ma <= {{2{PW00[15]}}, PW00}; mb <= lax18; end
		5'd1:  begin acc <= prod40; ma <= {{2{PW01[15]}}, PW01}; mb <= lay18; end
		5'd2:  begin acc <= acc_p; ma <= {{2{PW02[15]}}, PW02}; mb <= laz18; end
		5'd3:  begin shx <= WX_Q4 + acc16[16:0]; acc <= acc_p; end
		5'd4:  begin tpx <= WX_Q4 + acc16[16:0]; ma <= {{2{PW10[15]}}, PW10}; mb <= lax18; end
		5'd5:  begin acc <= prod40; ma <= {{2{PW11[15]}}, PW11}; mb <= lay18; end
		5'd6:  begin acc <= acc_p; ma <= {{2{PW12[15]}}, PW12}; mb <= laz18; end
		5'd7:  begin shy <= WY_Q4 - acc16[16:0]; acc <= acc_p; end
		5'd8:  begin tpy <= WY_Q4 - acc16[16:0]; end
		5'd9:  begin wdx <= {tpx[16], tpx} - {WX_Q4[16], WX_Q4}; wdy <= {tpy[16], tpy} - {WY_Q4[16], WY_Q4}; end
		5'd10: begin ma <= wdx; mb <= wdx; end
		5'd11: begin acc <= prod40; ma <= wdy; mb <= wdy; end
		5'd12: begin sq_start <= 1'b1; sq_v <= acc_p[31:0]; end
		5'd13: if (sq_done) dlen <= sq_r; else k <= k;
		5'd14: if (dlen < HEAD_Q4) begin
				head_ok <= 1'b0;
				h1x <= tpx; h1y <= tpy; h2x <= tpx; h2y <= tpy;
				phase <= P_SEG; k <= 5'd0; idx <= 4'd0;
			end else begin head_ok <= 1'b1; ma <= wdx; mb <= {2'b00, HEAD_Q4}; end
		5'd15: begin
			div_start <= 1'b1; div_num <= prod_abs[31:0]; div_den <= dlen; vsg <= prod40[39];
			ma <= wdy; mb <= {2'b00, HEAD_Q4};
		end
		5'd16: if (div_done) begin
				ux <= vsg ? -q16s : q16s;
				div_start <= 1'b1; div_num <= prod_abs[31:0]; div_den <= dlen; vsg <= prod40[39];
			end else k <= k;
		5'd17: if (div_done) uy <= vsg ? -q16s : q16s; else k <= k;
		5'd18: begin ma <= ux18; mb <= {{2{C30[15]}}, C30}; end
		5'd19: begin pA <= prod[31:0]; ma <= uy18; mb <= {{2{S30[15]}}, S30}; end
		5'd20: begin pB <= prod[31:0]; ma <= ux18; mb <= {{2{S30[15]}}, S30}; end
		5'd21: begin pC <= prod[31:0]; ma <= uy18; mb <= {{2{C30[15]}}, C30}; end
		5'd22: begin pD <= prod[31:0]; end
		default: begin
			h1x <= tpx + hs1s[16:0]; h1y <= tpy + hs2s[16:0];
			h2x <= tpx + hs3s[16:0]; h2y <= tpy + hs4s[16:0];
			phase <= P_SEG; k <= 5'd0; idx <= 4'd0;
		end
	endcase

	// the 8 segments of the widget as line units with a bounding box
	P_SEG: case (k)
		5'd0: begin s0x <= p0x; s0y <= p0y; s1x <= p1x; s1y <= p1y; end
		5'd1: begin sdx <= {s1x[16], s1x} - {s0x[16], s0x}; sdy <= {s1y[16], s1y} - {s0y[16], s0y}; end
		5'd2: begin ma <= 18'sd8 - {s0x[16], s0x}; mb <= sdy; end
		5'd3: begin acc <= prod40; ma <= 18'sd8 - {s0y[16], s0y}; mb <= sdx; end
		default: begin
			sg_c[idx[2:0]] <= acc_m[31:0];
			sg_dx[idx[2:0]] <= sdx;
			sg_dy[idx[2:0]] <= sdy;
			sg_t[idx[2:0]] <= seg_t;
			sg_xmin[idx[2:0]] <= clampv(lo_x, 10'd386, 10'd640);
			sg_xmax[idx[2:0]] <= clampv(hi_x, 10'd385, 10'd639);
			sg_ymin[idx[2:0]] <= clampv(lo_y, 10'd224, 10'd480);
			sg_ymax[idx[2:0]] <= clampv(hi_y, 10'd223, 10'd479);
			sg_valid[idx[2:0]] <= (idx == 4'd1 || idx == 4'd2) ? head_ok : 1'b1;
			sg_dash[idx[2:0]] <= (idx == 4'd3 || idx == 4'd4);
			sg_rgb[idx[2:0]] <= seg_rgb;
			k <= 5'd0;
			if (idx == 4'd7) begin phase <= P_DIG; idx <= 4'd0; end
			else idx <= idx + 4'd1;
		end
	endcase

	// binary to BCD: the 7 numbers (4 digits kept) and |ax| |ay| |az| (5 digits)
	P_DIG: case (k)
		5'd0: begin
			bcd_start <= 1'b1;
			bcd_bin <= (idx < 4'd7) ? numv[idx[2:0]] : (idx == 4'd7) ? abs_ax : (idx == 4'd8) ? abs_ay : abs_az;
		end
		default: if (bcd_done) begin
				if (idx < 4'd7) bcd4[idx[2:0]] <= bcd_out[15:0];
				else bcd5[bi4[1:0]] <= bcd_out;
				k <= 5'd0;
				if (idx == 4'd9) phase <= P_DONE;
				else idx <= idx + 4'd1;
			end else k <= k;
	endcase

	default: begin						// P_DONE
		done <= 1'b1;
		busy <= 1'b0;
		phase <= P_IDLE;
		k <= 5'd0;
	end

	endcase
end

endmodule

