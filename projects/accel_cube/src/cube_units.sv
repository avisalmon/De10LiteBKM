// The three sequential arithmetic units cube_math.sv shares: a divider, a square root and a CORDIC.
// Each takes `start` (one clock), works 16 clocks, then raises `done` for one clock with the result held.
// Bit-exact mirrors of sdiv / isqrt / cordic in assets/model.py.
// ***********************************************
`default_nettype none

// q = num / den, unsigned, truncated. Requires num[31:16] < den (so q fits 16 bits); the caller applies the sign.
module cube_div (
	input		wire				clk,
	input		wire				rst,
	input		wire				start,
	input		wire	[31:0]	num,
	input		wire	[15:0]	den,
	output	logic	[15:0]	q,
	output	logic				done,
	output	logic				busy
	);

logic	[15:0]	rem;				// partial remainder, always < den
logic	[15:0]	low;				// numerator bits still to shift in
logic	[15:0]	d;
logic	[3:0]		cnt;
wire	[16:0]	trial = {rem, low[15]};
wire	[16:0]	diff = trial - {1'b0, d};
wire				ge = trial >= {1'b0, d};

always_ff @(posedge clk) begin
	done <= 1'b0;
	if (rst) begin
		busy <= 1'b0;
		cnt <= 4'd0;
	end else if (start) begin
		rem <= num[31:16];
		low <= num[15:0];
		d <= den;
		cnt <= 4'd0;
		busy <= 1'b1;
	end else if (busy) begin
		rem <= ge ? diff[15:0] : trial[15:0];
		low <= {low[14:0], 1'b0};
		q <= {q[14:0], ge};
		cnt <= cnt + 4'd1;
		if (cnt == 4'd15) begin
			busy <= 1'b0;
			done <= 1'b1;
		end
	end
end

endmodule


// r = floor(sqrt(v)), two bits of v per clock.
module cube_sqrt (
	input		wire				clk,
	input		wire				rst,
	input		wire				start,
	input		wire	[31:0]	v,
	output	logic	[15:0]	r,
	output	logic				done,
	output	logic				busy
	);

logic	[31:0]	x;					// bits still to shift in, two at a time
logic	[17:0]	rem;				// remainder, always <= 2r
logic	[3:0]		cnt;
wire	[19:0]	trial = {rem, x[31:30]};
wire	[19:0]	sub = {2'b00, r, 2'b01};				// 4r + 1
wire	[19:0]	diff = trial - sub;
wire				ge = trial >= sub;

always_ff @(posedge clk) begin
	done <= 1'b0;
	if (rst) begin
		busy <= 1'b0;
		cnt <= 4'd0;
	end else if (start) begin
		x <= v;
		rem <= 18'd0;
		r <= 16'd0;
		cnt <= 4'd0;
		busy <= 1'b1;
	end else if (busy) begin
		rem <= ge ? diff[17:0] : trial[17:0];
		r <= {r[14:0], ge};
		x <= {x[29:0], 2'b00};
		cnt <= cnt + 4'd1;
		if (cnt == 4'd15) begin
			busy <= 1'b0;
			done <= 1'b1;
		end
	end
end

endmodule


// CORDIC, 16 iterations. x, y in Q16 (Q14 with 2 guard bits), z an angle in BAM16 with 4 fraction bits (wraps at
// 20 bits). vec = 1: vectoring, drives y to 0 and z accumulates atan2(y, x). vec = 0: rotation, drives z to 0
// and turns (x, y) by the start angle.
module cube_cordic (
	input		wire						clk,
	input		wire						rst,
	input		wire						start,
	input		wire						vec,
	input		wire	signed	[19:0]	x0,
	input		wire	signed	[19:0]	y0,
	input		wire	signed	[19:0]	z0,
	output	logic	signed	[19:0]	x,
	output	logic	signed	[19:0]	y,
	output	logic	signed	[19:0]	z,
	output	logic						done,
	output	logic						busy
	);

// Generated by assets/model.py constants (atan table, BAM16 << 4)
function automatic [19:0] atan_z(input [3:0] i);
	case (i)
		4'd0: atan_z = 20'd131072;
		4'd1: atan_z = 20'd77376;
		4'd2: atan_z = 20'd40884;
		4'd3: atan_z = 20'd20753;
		4'd4: atan_z = 20'd10417;
		4'd5: atan_z = 20'd5213;
		4'd6: atan_z = 20'd2607;
		4'd7: atan_z = 20'd1304;
		4'd8: atan_z = 20'd652;
		4'd9: atan_z = 20'd326;
		4'd10: atan_z = 20'd163;
		4'd11: atan_z = 20'd81;
		4'd12: atan_z = 20'd41;
		4'd13: atan_z = 20'd20;
		4'd14: atan_z = 20'd10;
		4'd15: atan_z = 20'd5;
		default: atan_z = 20'd0;
	endcase
endfunction

logic	[3:0]					cnt;
logic							mode_vec;
wire	signed	[19:0]	xs = x >>> cnt;
wire	signed	[19:0]	ys = y >>> cnt;
wire	signed	[19:0]	az = $signed(atan_z(cnt));
wire							cw = mode_vec ? !y[19] : z[19];		// turn clockwise

always_ff @(posedge clk) begin
	done <= 1'b0;
	if (rst) begin
		busy <= 1'b0;
		cnt <= 4'd0;
	end else if (start) begin
		x <= x0;
		y <= y0;
		z <= z0;
		mode_vec <= vec;
		cnt <= 4'd0;
		busy <= 1'b1;
	end else if (busy) begin
		if (cw) begin
			x <= x + ys;
			y <= y - xs;
			z <= z + az;
		end else begin
			x <= x - ys;
			y <= y + xs;
			z <= z - az;
		end
		cnt <= cnt + 4'd1;
		if (cnt == 4'd15) begin
			busy <= 1'b0;
			done <= 1'b1;
		end
	end
end

endmodule

`default_nettype wire
