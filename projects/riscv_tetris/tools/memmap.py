"""The system's memory map: one place, shared by the assembler, the C compiler, the simulator and the C header.
The RTL (src/rv32_soc.sv) has the same numbers; tests/test_memmap.py checks they agree.

  0x0000_0000  RAM        32 KB, code + data + stack (stack grows down from the top)
  0x1000_0000  TEXT       80 x 60 cells, one 32-bit word per cell: bits [7:0] character, [11:8] foreground colour,
                          [15:12] background colour; address = TEXT + (row * 80 + col) * 4. Write only.
  0x2000_0000  I/O        registers below, 32-bit each
"""

RAM_BASE = 0x0000_0000
RAM_SIZE = 32 * 1024
TEXT_BASE = 0x1000_0000
TEXT_COLS, TEXT_ROWS = 80, 60
IO_BASE = 0x2000_0000

IO = {
    "BUTTONS": 0x00,   # r: bit 0 A, 1 B, 2 Select, 3 Start, 4 Down, 5 Up, 6 Right, 7 Left, 8 KEY0, 9 KEY1 (1 = held)
    "FRAME":   0x04,   # r: frame counter, +1 every vertical sync (60 Hz)
    "RANDOM":  0x08,   # r: a free-running 32-bit LFSR
    "HEX":     0x0C,   # w: six hex digits on HEX5..HEX0 (write BCD to show decimal)
    "LEDS":    0x10,   # w: LEDR9..0
    "BUZZER":  0x14,   # w: half period of the buzzer square wave in 25 MHz clocks; 0 = silent
    "UART":    0x18,   # w: send one byte to the PC (JTAG UART); r: bit 0 = busy (wait before the next write)
    "SWITCHES": 0x1C,  # r: SW9..0
    "CYCLES":  0x20,   # r: 25 MHz cycle counter
    "EXIT":    0x24,   # w: stop the CPU (simulation and the board); the value is the exit code
}

# the 16-colour palette, RGB444 (CGA order), index = colour nibble
PALETTE = [0x000, 0x00A, 0x0A0, 0x0AA, 0xA00, 0xA0A, 0xA50, 0xAAA,
           0x555, 0x55F, 0x5F5, 0x5FF, 0xF55, 0xF5F, 0xFF5, 0xFFF]

# characters 0x80.. are block glyphs drawn by the screen itself (not from the font):
BLOCK_FULL, BLOCK_INNER, BLOCK_SHADE, BLOCK_FRAME = 0x80, 0x81, 0x82, 0x83


def c_header():
    lines = ["/* GENERATED by tools/memmap.py: the memory map. Edit that file, not this one. */",
             "#ifndef SOC_H", "#define SOC_H",
             f"#define RAM_SIZE {RAM_SIZE}", f"#define TEXT_BASE 0x{TEXT_BASE:08X}",
             f"#define TEXT_COLS {TEXT_COLS}", f"#define TEXT_ROWS {TEXT_ROWS}", f"#define IO_BASE 0x{IO_BASE:08X}"]
    for name, off in IO.items():
        lines.append(f"#define IO_{name} (*(volatile int *)0x{IO_BASE + off:08X})")
    lines += ["#define BTN_A 1", "#define BTN_B 2", "#define BTN_SELECT 4", "#define BTN_START 8", "#define BTN_DOWN 16",
              "#define BTN_UP 32", "#define BTN_RIGHT 64", "#define BTN_LEFT 128", "#define BTN_KEY0 256", "#define BTN_KEY1 512",
              f"#define BLOCK_FULL 0x{BLOCK_FULL:02X}", f"#define BLOCK_INNER 0x{BLOCK_INNER:02X}",
              f"#define BLOCK_SHADE 0x{BLOCK_SHADE:02X}", f"#define BLOCK_FRAME 0x{BLOCK_FRAME:02X}",
              "#define CELL(ch, fg, bg) ((ch) | ((fg) << 8) | ((bg) << 12))",
              "#define TEXT_AT(row, col) (*(volatile int *)(TEXT_BASE + ((row) * TEXT_COLS + (col)) * 4))",
              "#endif"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import sys
    from pathlib import Path
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "sw" / "soc.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(c_header(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")
