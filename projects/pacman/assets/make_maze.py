"""Pac-Man maze -> the Verilog tile table and the wall picture ROM.

    python assets/make_maze.py        (from my_designs/pacman)

Writes:
  src/maze_tiles.sv      the 28x31 tile map as a combinational table: wall / dot / power bits per row
  assets/walls.bin       the wall picture ($readmemb), 2 bits per pixel (0 empty, 1 wall line, 2 ghost-house door),
                         240 rows (maze pixel rows 4..243: the outer border shows as one line) x 256 (224 used)
  assets/maze_preview.png  what the screen should look like (walls + dots), to check by eye
"""
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

# The arcade maze, 28 x 31 tiles: '#' wall, '.' dot, 'o' power pellet, '-' ghost-house door, ' ' open
MAZE = [
    "############################",
    "#............##............#",
    "#.####.#####.##.#####.####.#",
    "#o####.#####.##.#####.####o#",
    "#.####.#####.##.#####.####.#",
    "#..........................#",
    "#.####.##.########.##.####.#",
    "#.####.##.########.##.####.#",
    "#......##....##....##......#",
    "######.##### ## #####.######",
    "     #.##### ## #####.#     ",
    "     #.##          ##.#     ",
    "     #.## ###--### ##.#     ",
    "######.## #      # ##.######",
    "      .   #      #   .      ",
    "######.## #      # ##.######",
    "     #.## ######## ##.#     ",
    "     #.##          ##.#     ",
    "     #.## ######## ##.#     ",
    "######.## ######## ##.######",
    "#............##............#",
    "#.####.#####.##.#####.####.#",
    "#.####.#####.##.#####.####.#",
    "#o..##.......  .......##..o#",
    "###.##.##.########.##.##.###",
    "###.##.##.########.##.##.###",
    "#......##....##....##......#",
    "#.##########.##.##########.#",
    "#.##########.##.##########.#",
    "#..........................#",
    "############################",
]
W, H, T = 28, 31, 8
assert len(MAZE) == H and all(len(r) == W for r in MAZE), [len(r) for r in MAZE]


def tile(c, r):
    return MAZE[r][c] if 0 <= c < W and 0 <= r < H else " "   # outside the maze: open (draws the outer double line)


def bits(ch_set, r):
    return sum(1 << c for c in range(W) if MAZE[r][c] in ch_set)


# ---- the tile table: walls block movement ('#' and the door), dots and power pellets
rows = []
for r in range(H):
    rows.append(f"\t\t5'd{r}: begin wall = 28'h{bits('#-', r):07X}; dot = 28'h{bits('.', r):07X}; "
                f"power = 28'h{bits('o', r):07X}; end")
dots = sum(row.count(".") for row in MAZE)
power = sum(row.count("o") for row in MAZE)
sv = f"""// Pac-Man tile map, 28 x 31 (bit c = column c). GENERATED by assets/make_maze.py: edit that, not this.
// {dots} dots + {power} power pellets = {dots + power} to eat.
`default_nettype none

module maze_tiles (
	input		wire	[4:0]		row,
	output	logic	[27:0]	wall,		// 1 = blocks Pac-Man and the ghosts (walls and the house door)
	output	logic	[27:0]	dot,
	output	logic	[27:0]	power
	);

always_comb begin
	wall = 28'hFFFFFFF; dot = 28'h0; power = 28'h0;
	case (row)
{chr(10).join(rows)}
		default: ;
	endcase
end

endmodule
"""
(HERE / "src" / "maze_tiles.sv").write_text(sv, encoding="utf-8", newline="\n")


# ---- the wall picture: a thin line 2..3 pixels inside every wall edge (rounded on outer corners), like the
# arcade: walls 2 tiles thick become outlined blocks, walls 1 tile thick (house, border) become double lines.
def open_tile(c, r):
    return tile(c, r) not in "#"           # the door counts as open here, so the house walls end at it


def dist_to_open(x, y):
    """Distance from pixel centre (x+.5, y+.5) to the nearest open tile square."""
    px, py = x + 0.5, y + 0.5
    c0, r0 = x // T, y // T
    best = 99.0
    for r in range(r0 - 1, r0 + 2):
        for c in range(c0 - 1, c0 + 2):
            if open_tile(c, r):
                dx = max(c * T - px, 0, px - (c + 1) * T)
                dy = max(r * T - py, 0, py - (r + 1) * T)
                best = min(best, math.hypot(dx, dy))
    return best


pic = [[0] * (W * T) for _ in range(H * T)]
for y in range(H * T):
    for x in range(W * T):
        c, r = x // T, y // T
        if tile(c, r) == "-":
            pic[y][x] = 2 if y % T in (3, 4) else 0
        elif tile(c, r) == "#" and 2.0 <= dist_to_open(x, y) < 3.0:
            pic[y][x] = 1

# binary, 2 digits per entry: a 2-bit ROM loaded from hex gets one Quartus warning (10230) per line
with open(HERE / "assets" / "walls.bin", "w", newline="\n") as f:
    for y in range(4, 4 + 240):                   # screen row 0 = maze pixel row 4
        for x in range(256):
            f.write(f"{pic[y][x] if x < W * T else 0:02b}\n")

try:
    from PIL import Image
    img = Image.new("RGB", (W * T, 240))
    for y in range(4, 4 + 240):
        for x in range(W * T):
            c, r = x // T, y // T
            col = {1: (33, 33, 222), 2: (255, 184, 255)}.get(pic[y][x], (0, 0, 0))
            u, v = x % T, y % T
            if tile(c, r) == "." and u in (3, 4) and v in (3, 4):
                col = (255, 204, 187)
            if tile(c, r) == "o" and (2 * u - 7) ** 2 + (2 * v - 7) ** 2 <= 50:
                col = (255, 204, 187)
            img.putpixel((x, y - 4), col)
    img.resize((W * T * 3, 240 * 3), Image.NEAREST).save(HERE / "assets" / "maze_preview.png")
except ImportError:
    pass
print(f"maze_tiles.sv: {dots} dots + {power} power; walls.bin: 240 x 256; maze_preview.png")
