"""The skills are the BKM's brain and ship in two places (Claude Code and GitHub Copilot).
These tests keep them valid, identical, discoverable, and reachable in Hebrew."""

import re
from pathlib import Path

import pytest
import sync_skills as sync

ROOT = Path(__file__).resolve().parent.parent
CLAUDE = ROOT / ".claude" / "skills"
COPILOT = ROOT / ".github" / "skills"
GUIDE = "de10-lite-guide"
CORE = {GUIDE, "setup-my-computer", "mentor", "improve-this-guide"}  # every BKM has these
ALL = {p.name for p in CLAUDE.iterdir() if p.is_dir()}


def test_every_bkm_has_the_core_skills():
    assert CORE <= ALL, f"missing: {CORE - ALL}"


@pytest.mark.parametrize("name", sorted(ALL))
def test_skill_frontmatter_is_valid_for_both_tools(name):
    meta = sync.parse_frontmatter((CLAUDE / name / "SKILL.md").read_text(encoding="utf-8"))
    assert meta["name"] == name
    assert re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name) and len(name) <= 64
    assert 40 <= len(meta["description"]) <= 1024  # Copilot's limit
    assert "TRIGGER:" in meta["description"], "a skill nobody can trigger is dead weight"


@pytest.mark.parametrize("name", sorted(ALL - {"improve-this-guide"}))
def test_user_skills_have_trigger_words(name):
    # This BKM is English only (Avi, 2026-10-24): the template's Hebrew-trigger check became "has quoted triggers".
    description = sync.parse_frontmatter((CLAUDE / name / "SKILL.md").read_text(encoding="utf-8"))["description"]
    assert len(re.findall(r'"[^"]+"', description.partition("TRIGGER:")[2])) >= 3, f"{name} has too few triggers"


def test_the_copilot_copy_is_identical_to_the_claude_source():
    assert sync.drift() == [], "run: python scripts/sync_skills.py"


def test_a_skill_edit_that_is_not_synced_is_caught():
    """A guard that cannot be tripped is worthless: prove the drift check notices."""
    skill = CLAUDE / "mentor" / "SKILL.md"
    original = skill.read_bytes()
    try:
        skill.write_bytes(original + b"\nan unsynced edit\n")
        assert any("mentor" in problem for problem in sync.drift())
    finally:
        skill.write_bytes(original)
    assert sync.drift() == []


def test_instructions_files_index_every_skill():
    for target in sync.INSTRUCTION_FILES:
        text = target.read_text(encoding="utf-8")
        assert "GENERATED by scripts/sync_skills.py" in text
        for name in ALL:
            assert f"`{name}`" in text and f".github/skills/{name}/SKILL.md" in text, (target.name, name)


def test_the_guide_hands_over_to_every_other_skill():
    text = (CLAUDE / GUIDE / "SKILL.md").read_text(encoding="utf-8")
    for name in ALL - {GUIDE}:
        assert f"`{name}`" in text, f"{GUIDE} never mentions {name}"


def test_claude_md_routes_to_every_skill_and_keeps_the_standing_rules():
    text = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    for name in ALL:
        assert f"`{name}`" in text, f"CLAUDE.md never routes to {name}"
    for rule in ("check_updates.py", "English", "env/", "my_designs/", "Tell the truth"):
        assert rule in text, rule
